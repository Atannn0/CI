// Generates the seed migrations from data/seed-quizzes.json (the merged, deduplicated and verified
// catalog). Run with `npm run seed:sql`. Entries without a "migration" field belong to
// 002_seed_quizzes.sql; later additions name their own migration (e.g. "004_seed_more_tests"), so a
// published migration never changes. Every insert skips URLs already in the database, so running
// the import again adds no duplicates.
import { readFile, writeFile } from "node:fs/promises";

const FORMATS = new Set(["text", "image", "mixed"]);
const TYPES = new Set(["personality", "preference", "knowledge", "logic"]);
const LANGUAGES = new Set([
  "cs", "en", "sk", "de", "pl", "fr", "es", "it", "pt", "nl", "ru", "uk", "ja", "zh", "ko",
  "hu", "ro", "sv", "da", "fi", "no", "el", "tr", "ar", "he", "hi", "th", "vi", "id", "ms",
  "bg", "hr", "sr", "sl", "lt", "lv", "et",
]);
const BASE_MIGRATION = "002_seed_quizzes";

function urlKey(value) {
  const url = new URL(value.trim());
  const host = url.hostname.toLowerCase().replace(/^www\./, "");
  const port = url.port ? `:${url.port}` : "";
  const path = url.pathname.replace(/\/+$/, "");
  const params = [...url.searchParams.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(v)}`)
    .join("&");
  return `${host}${port}${path}${params ? `?${params}` : ""}`;
}

const lit = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const quizzes = JSON.parse(await readFile("data/seed-quizzes.json", "utf8"));
const seen = new Set();
const groups = new Map();
for (const q of quizzes) {
  if (!FORMATS.has(q.format) || !LANGUAGES.has(q.language) || !q.types.length || !q.types.every((t) => TYPES.has(t))) {
    throw new Error(`Invalid seed entry: ${q.title}`);
  }
  const key = urlKey(q.url);
  if (seen.has(key)) throw new Error(`Duplicate seed URL: ${q.url}`);
  seen.add(key);
  const migration = q.migration ?? BASE_MIGRATION;
  if (!/^\d{3}_[a-z0-9_]+$/.test(migration)) throw new Error(`Invalid migration name for ${q.title}: ${migration}`);
  if (migration === BASE_MIGRATION && q.is_collection) throw new Error(`${BASE_MIGRATION} has no is_collection column`);
  const types = `array[${q.types.map(lit).join(", ")}]::text[]`;
  const values = [lit(q.title), lit(q.url), lit(key), lit(q.description), lit(q.language), lit(q.format), types, lit(q.topic), "true"];
  if (migration !== BASE_MIGRATION) {
    values.push(q.is_collection ? "true" : "false");
    if (migration >= "006") values.push(lit(q.source ?? null));
  }
  if (!groups.has(migration)) groups.set(migration, []);
  groups.get(migration).push(`  (${values.join(", ")})`);
}

/** Published seed migrations must not be rewritten (preview/prod may have already applied them). */
const FROZEN = new Set(["002_seed_quizzes", "004_seed_requested_tests"]);

for (const [migration, rows] of groups) {
  if (FROZEN.has(migration)) {
    console.log(`seed: skip frozen migrations/${migration}.sql (${rows.length} entries)`);
    continue;
  }
  let columns = "title, url, url_key, description, language, format, types, topic, verified";
  if (migration !== BASE_MIGRATION) columns += ", is_collection";
  if (migration >= "006") columns += ", source";
  let sql = `-- Generated by scripts/build-seed.mjs from data/seed-quizzes.json. Do not edit by hand.
insert into quizzes (${columns}) values
${rows.join(",\n")}
on conflict (url_key) do nothing;
`;
  if (migration === "006_seed_idrlabs_ja_zh") {
    sql += `
-- After individual IDRlabs tests are present, hide the hub card from the public catalog.
update quizzes set hidden = true where url_key = 'idrlabs.com' and hidden = false;
`;
  }
  await writeFile(`migrations/${migration}.sql`, sql);
  console.log(`seed: wrote ${rows.length} quizzes to migrations/${migration}.sql`);
}
